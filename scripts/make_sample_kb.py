# 文件构建（docx / pdf 共用同一份 markdown 单元文本）
# ═══════════════════════════════════════════════════════════════════════
def _add_table(doc, headers: list[str], rows: list[tuple]) -> None:
    """自选表头表格（Table Grid 带边框，解析器可稳定识别为 TABLE 块）。"""
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    for i, t in enumerate(headers):
        table.rows[0].cells[i].text = t
    for r in rows:
        cells = table.add_row().cells
        for i, v in enumerate(r):
            cells[i].text = v


def _setup_docx_styles(doc) -> None:
    from docx.shared import Pt, RGBColor
    normal = doc.styles["Normal"]
    mt._set_cn(normal, "宋体", size=12)
    normal.paragraph_format.line_spacing = 1.5
    normal.paragraph_format.first_line_indent = Pt(24)
    for name, sz in (("Heading 1", 16), ("Heading 2", 14), ("Heading 3", 13), ("Heading 4", 12)):
        h = doc.styles[name]
        mt._set_cn(h, "黑体", size=sz, bold=True, color=RGBColor(0, 0, 0))
        h.paragraph_format.first_line_indent = Pt(0)


def build_docx_file(out_path: Path, title: str, units, units_text: dict[str, str]) -> None:
    from docx import Document
    doc = Document()
    _setup_docx_styles(doc)
    doc.add_heading(title, level=1)
    for key, _section, _points, _chars in units:
        if key in units_text:
            mt._add_markdown_unit(doc, key, units_text[key])
            if key in UNIT_TABLES:
                headers, rows = UNIT_TABLES[key]
                _add_table(doc, headers, rows)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(out_path))
    print(f"[OK] {out_path.name}")


def build_pdf_file(out_path: Path, title: str, units, units_text: dict[str, str]) -> None:
    w = mt.PdfWriter()
    w.para(title, size=18, bold=True, indent=False, spacing=16)
    for key, _section, _points, _chars in units:
        text = units_text.get(key, "")
        for raw in text.splitlines():
            line = raw.strip()
            if not line:
                continue
            if line.startswith("### "):
                w.chapter(line[4:])
            elif line.startswith("- "):
                w.para(line[2:], indent=True)
            else:
                w.para(line, indent=True)
    w.finish(out_path)


